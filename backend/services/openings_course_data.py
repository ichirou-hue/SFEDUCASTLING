"""Данные модуля «Дебюты»: 30 дебютов, развилки и вариации.

Каждый урок описывает общую линию (ходы до развилки) и 2-3 вариации.
Задание строится из SAN-хода: FEN, ``source_square`` и UCI-эталон
вычисляются python-chess, поэтому в данных нет продублированных
позиций и эталонных ходов - рассинхронизировать их нельзя.

Формат шага линии:

- кортеж ``(SAN, заголовок, инструкция, пояснение)`` - ход игрока
  (белых), из него создаётся учебное задание;
- строка ``"SAN"`` - ответ соперника, задание не создаётся.

Развилка (вариация) начинается с ответа соперника: именно он и
определяет, по какой ветке пойдёт урок. Клиент проигрывает этот ход
на доске и показывает задания выбранной ветки.
"""

from __future__ import annotations

import chess

Step = str | tuple[str, str, str, str]


def _task(
    board: chess.Board,
    move: chess.Move,
    *,
    order: int,
    difficulty: int,
    title: str,
    instruction: str,
    explanation: str,
    branch: str | None,
) -> dict:
    piece = board.piece_at(move.from_square)
    payload: dict = {
        "piece": piece.symbol().upper() if piece else "P",
        "mode": "accepted_moves",
        "accepted_moves": [move.uci()],
    }
    if branch:
        payload["branch"] = branch
    return {
        "task_type": "make_move",
        "title": title,
        "instruction": instruction,
        "fen": board.fen(),
        "source_square": chess.square_name(move.from_square),
        "difficulty": difficulty,
        "payload": payload,
        "explanation": explanation,
        "sort_order": order,
    }


def _play(
    board: chess.Board,
    step: Step,
    *,
    branch: str | None,
    order: int,
    difficulty: int,
    tasks: list[dict],
    sans: list[str],
) -> None:
    if isinstance(step, tuple):
        san, title, instruction, explanation = step
        move = board.parse_san(san)
        tasks.append(
            _task(
                board,
                move,
                order=order,
                difficulty=difficulty,
                title=title,
                instruction=instruction,
                explanation=explanation,
                branch=branch,
            )
        )
        board.push(move)
        sans.append(san)
        return

    move = board.parse_san(step)
    board.push(move)
    sans.append(step)


def _line_text(start: chess.Board, sans: list[str]) -> str:
    """Нотационная запись ветки: ``3...Bc5 4.c3 Nf6 5.d4``."""
    board = start.copy()
    parts: list[str] = []
    for index, san in enumerate(sans):
        number = board.fullmove_number
        if board.turn == chess.WHITE:
            parts.append(f"{number}.{san}")
        elif index == 0:
            # Ветка начинается с хода соперника - только тут нужен "N...".
            parts.append(f"{number}...{san}")
        else:
            parts.append(san)
        board.push(board.parse_san(san))
    return " ".join(parts)


def _lesson(
    *,
    slug: str,
    title: str,
    section: str,
    order: int,
    theory: str,
    line: list[Step],
    variations: list[dict],
) -> dict:
    board = chess.Board()
    tasks: list[dict] = []
    common_sans: list[str] = []
    player_move = 0

    for step in line:
        player_move += 1 if isinstance(step, tuple) else 0
        _play(
            board,
            step,
            branch=None,
            order=len(tasks) + 1,
            difficulty=min(3, 1 + player_move // 3),
            tasks=tasks,
            sans=common_sans,
        )

    base_fen = board.fen()
    base_board = board.copy()
    variations_meta: list[dict] = []

    for index, variation in enumerate(variations, start=1):
        branch_board = base_board.copy()
        steps = list(variation["line"])
        intro_san = None
        intro_move = None

        if steps and not isinstance(steps[0], tuple):
            intro_san = steps.pop(0)
            move = branch_board.parse_san(intro_san)
            intro_move = move.uci()
            branch_board.push(move)

        branch_tasks: list[dict] = []
        branch_sans: list[str] = [intro_san] if intro_san else []
        branch_move = 0
        for step in steps:
            branch_move += 1 if isinstance(step, tuple) else 0
            _play(
                branch_board,
                step,
                branch=variation["id"],
                order=100 * index + len(branch_tasks) + 1,
                difficulty=min(3, 1 + branch_move // 3),
                tasks=branch_tasks,
                sans=branch_sans,
            )

        tasks.extend(branch_tasks)
        variations_meta.append(
            {
                "id": variation["id"],
                "label": variation["label"],
                "description": variation.get("description", ""),
                "fen": base_fen,
                "intro_move": intro_move,
                "intro_san": intro_san,
                "line": _line_text(base_board, branch_sans),
            }
        )

    return {
        "slug": slug,
        "title": title,
        "section_title": section,
        "theory": theory,
        "sort_order": order,
        "variations": variations_meta,
        "tasks": tasks,
    }



def _options(*pairs: tuple[str, str]) -> list[dict[str, str]]:
    return [{"id": option_id, "label": label} for option_id, label in pairs]


def _piece_at(fen: str, square: str) -> str:
    """Символ фигуры на клетке: нужен для payload.piece заданий."""
    board = chess.Board(fen)
    piece = board.piece_at(chess.parse_square(square))
    if piece is None:
        raise ValueError(f"На клетке {square} нет фигуры: {fen}")
    return piece.symbol().upper()


def _select(
    title: str,
    instruction: str,
    fen: str,
    source: str,
    explanation: str,
    *,
    mode: str = "all_legal_moves",
) -> dict:
    return {
        "task_type": "select_squares",
        "title": title,
        "instruction": instruction,
        "fen": fen,
        "source_square": source,
        "payload": {"piece": _piece_at(fen, source), "mode": mode},
        "explanation": explanation,
    }


def _move(
    title: str,
    instruction: str,
    fen: str,
    source: str,
    explanation: str,
    *,
    mode: str = "accepted_moves",
    accepted: list[str] | None = None,
) -> dict:
    payload: dict = {"piece": _piece_at(fen, source), "mode": mode}
    if accepted is not None:
        payload["accepted_moves"] = accepted
    return {
        "task_type": "make_move",
        "title": title,
        "instruction": instruction,
        "fen": fen,
        "source_square": source,
        "payload": payload,
        "explanation": explanation,
    }


def _choose(
    title: str,
    instruction: str,
    fen: str,
    options: list[dict[str, str]],
    correct: str,
    explanation: str,
) -> dict:
    return {
        "task_type": "choose_option",
        "title": title,
        "instruction": instruction,
        "fen": fen,
        "source_square": None,
        "payload": {"options": options, "correct_option": correct},
        "explanation": explanation,
    }


def _lesson(
    slug: str,
    title: str,
    theory: str,
    tasks: list[dict],
    *,
    section: str | None = None,
) -> dict:
    normalized: list[dict] = []
    for index, task in enumerate(tasks, start=1):
        item = dict(task)
        item.setdefault("difficulty", min(3, 1 + (index - 1) // 2))
        item["sort_order"] = index
        normalized.append(item)
    return {
        "slug": slug,
        "title": title,
        "section_title": section,
        "theory": theory,
        "variations": [],
        "tasks": normalized,
    }


def _numbered(lessons: list[dict]) -> list[dict]:
    return [
        {**lesson, "sort_order": index}
        for index, lesson in enumerate(lessons, start=1)
    ]



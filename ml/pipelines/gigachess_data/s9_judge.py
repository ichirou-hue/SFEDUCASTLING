JUDGE_SYSTEM = """Ты строгий проверяющий шахматных комментариев. Дан план (факты, вычисленные программой и движком — считай их истинными) и итоговый текст, написанный по этому плану. Сам позицию не анализируй: суди только по плану и определениям.

Проверь:
1. faithful: в тексте нет утверждений, которых нет в плане; не перепутаны фигуры, цвета, клетки, кто кого бьёт; связки «потому что / в результате / однако» соединяют те же факты, что в плане (метки «причина:», «в результате:», «однако:» в плане); не изменён смысл вердикта и оценки.
2. intent_ok: если в плане есть цитата игрока в «», текст передаёт её как мнение игрока и по смыслу близко к цитате; если цитаты нет — null.
3. terms: для каждого термина из квадратных скобок плана — подходит ли он под определение, судя по фактам плана (fits: true/false) и короткое объяснение при false.
4. readable: 1–5, насколько текст читается как разбор тренера (5 — естественно и ясно, 1 — бессвязно).

Ответь одним JSON-объектом:
{"faithful": true|false, "faithfulness_issues": ["..."], "intent_ok": true|false|null, "terms": [{"term": "...", "fits": true|false, "why": "..."}], "readable": 1-5}"""


def judge_user(d: dict, answer: str) -> str:
    terms = re.findall(r"\[([^\]]+)\]", d["draft"])
    defs = "\n".join(f"- {t}: {TERM_DEFS[t]}" for t in terms if t in TERM_DEFS) or "- (терминов нет)"
    return f"Определения терминов:\n{defs}\n\nПлан:\n{d['draft']}\n\nИтоговый текст:\n{answer}"


def judge_one(client: LLMClient, d: dict, answer: str) -> dict:
    if STOP.is_set():
        raise LLMError("остановлено после ошибки оплаты или ключа")
    j = extract_json(client.complete(JUDGE_SYSTEM, judge_user(d, answer)))
    return {"id": d["id"], **j}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--drafts", required=True)
    ap.add_argument("--polished", required=True)
    ap.add_argument("--review", help="review.csv: берём строки набора random")
    ap.add_argument("--autocheck", help="autocheck.jsonl: добавляем всё помеченное")
    ap.add_argument("--all", action="store_true", help="судить все принятые разборы из --polished")
    ap.add_argument("--out", required=True)
    ap.add_argument("--concurrency", type=int, default=12)
    ap.add_argument("--count-only", action="store_true", help="только посчитать, сколько примеров уйдёт судье")
    ap.add_argument("--env", help="Environment file; defaults to repository root .env")
    args = ap.parse_args()
    load_env(args.env)

    ids, why = [], {}
    if args.review:
        for r in csv.DictReader(open(args.review, encoding="utf-8-sig"), delimiter=";"):
            if r["набор"] == "random":
                ids.append(r["id"]); why[r["id"]] = "random"
    if args.all:
        for r in read_jsonl(args.polished):
            if r.get("answer") and r["id"] not in why:
                ids.append(r["id"]); why[r["id"]] = "random"
    if args.autocheck:
        for r in read_jsonl(args.autocheck):
            if r["flags"] and r["id"] not in why:
                ids.append(r["id"]); why[r["id"]] = "autocheck"
    print(f"судье: {len(ids)} (random: {sum(v == 'random' for v in why.values())}, "
          f"помечены скриптами: {sum(v == 'autocheck' for v in why.values())})")
    if args.count_only:
        return

    drafts = {d["id"]: d for d in read_jsonl(args.drafts)}
    answers = {r["id"]: r["answer"] for r in read_jsonl(args.polished) if r.get("answer")}
    seen = done_ids(args.out)
    todo = [i for i in ids if i not in seen and i in answers]
    try:
        client = LLMClient(max_tokens=3000)
    except LLMError as e:
        sys.exit(f"LLM не настроен: {e}")
    lock = threading.Lock()
    ok = err = 0
    with ThreadPoolExecutor(args.concurrency) as pool:
        futs = {pool.submit(judge_one, client, drafts[i], answers[i]): i for i in todo}
        for fut in as_completed(futs):
            i = futs[fut]
            try:
                res = fut.result()
            except LLMError as e:
                err += 1
                print(f"[{i}] LLM: {e}", file=sys.stderr)
                if FATAL_RE.match(str(e)):
                    STOP.set()
                    pool.shutdown(wait=False, cancel_futures=True)
                    sys.exit(f"остановлено: {e}. Готовое сохранено, повторный запуск продолжит.")
                continue
            res["sample"] = why[i]
            with lock:
                write_jsonl(args.out, [res], append=True)
                ok += 1
    print(f"оценено: {ok}, ошибок API: {err}")


if __name__ == "__main__":
    main()

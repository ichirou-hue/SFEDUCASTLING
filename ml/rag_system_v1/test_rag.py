def run_comprehensive_benchmark():
    print("=" * 90)
    print(f" ЗАПУСК БЕНЧМАРКА RAG-ТРЕНЕРА: 20 СЦЕНАРИЕВ ПО ВСЕМ СТАДИЯМ И ТЕМАМ")
    print("=" * 90)

    total_time_ms = 0.0

    for item in TEST_SUITE:
        idx = item["id"]
        title = item["title"]
        stage = item["stage"]

        t_start = time.time()
        
        prompt = build_llm_rag_prompt(
            fen=item["fen"],
            sf_eval=item["sf_eval"],
            best_move_sf=item["best_move_sf"],
            played_move_human=item["played_move_human"],
            eval_after=item["eval_after"],
            stage=stage,
            mistake_type=item["mistake_type"],
            query_ctx=item["query_ctx"]
        )

        t_elapsed = (time.time() - t_start) * 1000
        total_time_ms += t_elapsed

        print(f"[{idx:02d}/20] ({stage.upper():<10}) {title[:45]:<45} | Время: {t_elapsed:5.1f} ms")

    avg_time = total_time_ms / len(TEST_SUITE)
    print("=" * 90)
    print(f"✓ ВСЕ 20 ТЕСТОВ УСПЕШНО ПРОЙДЕНЫ! Среднее время поиска: {avg_time:.2f} ms")
    print("=" * 90)

    # Демонстрация одного полного сгенерированного промпта
